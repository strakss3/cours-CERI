-- Table CLIENT
CREATE TABLE CLIENT (
    IdCLI INT PRIMARY KEY,
    NOM VARCHAR(255),
    ADR VARCHAR(255)
);

-- Table OBJ (objet)
CREATE TABLE OBJ (
    IdOBJ INT PRIMARY KEY,
    TXT VARCHAR(255),
    CAT VARCHAR(100)
);


-- Table DISTRA (textes distracteurs)
CREATE TABLE DISTRA (
    IdDISTRA INT PRIMARY KEY,
    TXT TEXT,
    SOURCE VARCHAR(255)
);

-- Table ADRMAIL (adresses email)
CREATE TABLE ADRMAIL (
    IdADR INT PRIMARY KEY,
    SOURCE VARCHAR(255),
    VALID BOOLEAN
);

-- Table CONTRAT
CREATE TABLE CONTRAT (
    IdCO INT PRIMARY KEY,
    IdCLI INT NOT NULL,
    IdOBJ INT NOT NULL,
    TXT TEXT,
    TYP VARCHAR(100),
    CATFROM VARCHAR(100),
    CONSTRAINT fk_contrat_client FOREIGN KEY (IdCLI) REFERENCES CLIENT(IdCLI),
    CONSTRAINT fk_contrat_obj FOREIGN KEY (IdOBJ) REFERENCES OBJ(IdOBJ)
);


-- Table CO_DISTRA (association contrat-distracteur)
CREATE TABLE CO_DISTRA (
    IdCO INT,
    IdDISTRA INT,
    PRIMARY KEY (IdCO, IdDISTRA),
    CONSTRAINT fk_codistra_contrat FOREIGN KEY (IdCO) REFERENCES CONTRAT(IdCO),
    CONSTRAINT fk_codistra_distra FOREIGN KEY (IdDISTRA) REFERENCES DISTRA(IdDISTRA)
);

-- Table CO_ADR (association contrat-adresse mail)
CREATE TABLE CO_ADR (
    IdCO INT,
    IdADR INT,
    PRIMARY KEY (IdCO, IdADR),
    CONSTRAINT fk_coadr_contrat FOREIGN KEY (IdCO) REFERENCES CONTRAT(IdCO),
    CONSTRAINT fk_coadr_adrmail FOREIGN KEY (IdADR) REFERENCES ADRMAIL(IdADR)
);